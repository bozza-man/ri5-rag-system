#!/usr/bin/env bash
# Configuration Setup Script for Pi5 RAG System
# This script helps you configure your development environment

set -euo pipefail

BOLD="\033[1m"
GREEN="\033[32m"
BLUE="\033[34m"
YELLOW="\033[33m"
RESET="\033[0m"

log() { echo -e "${BOLD}[config-setup]${RESET} $1" >&2; }
log_success() { echo -e "${GREEN}✓${RESET} $1" >&2; }
log_info() { echo -e "${BLUE}ℹ${RESET} $1" >&2; }
log_warning() { echo -e "${YELLOW}⚠${RESET} $1" >&2; }

interactive_setup() {
    log "Interactive Configuration Setup"
    log "=============================="
    echo ""
    
    # Get Pi5 IP address
    log_info "Enter your Pi5's IP address or hostname:"
    read -p "Pi5 Host (default: pi5.local): " pi5_host
    pi5_host=${pi5_host:-pi5.local}
    
    # Get username
    log_info "Enter your Pi5 username:"
    read -p "Username (default: pi): " pi5_user
    pi5_user=${pi5_user:-pi}
    
    # Get deployment path
    log_info "Enter the deployment path on your Pi5:"
    read -p "Path (default: /home/pi/ri5-rag-system): " pi5_path
    pi5_path=${pi5_path:-/home/pi/ri5-rag-system}
    
    # Create config file
    log "Creating configuration file..."
    cat > config.env << EOF
# Pi5 RAG System Configuration
# Generated by setup-config.sh on $(date)

# Production Server Configuration
PRODUCTION_HOST=${pi5_host}
PRODUCTION_USER=${pi5_user}
PRODUCTION_PATH=${pi5_path}

# Service Configuration
SERVICE_NAME=pi5-rag-app
CHROMA_SERVICE_NAME=pi5-rag-chroma

# Development Configuration
DEV_VENV_PATH=.venv
DEV_ENV_FILE=.env

# GitHub Configuration
GITHUB_REPO=bozza-man/ri5-rag-system
GITHUB_BRANCH=main

# SSH Configuration
SSH_KEY_PATH=~/.ssh/id_rsa
SSH_PORT=22

# Deployment Configuration
AUTO_DEPLOY_TIMER=5
DEPLOY_TIMEOUT=300

# Logging Configuration
LOG_LEVEL=INFO
LOG_FILE=deploy.log
EOF
    
    log_success "Configuration file created: config.env"
    
    # Test connection
    log "Testing connection to Pi5..."
    if ping -c 1 -W 1 "$pi5_host" >/dev/null 2>&1; then
        log_success "Pi5 is reachable at $pi5_host"
    else
        log_warning "Cannot reach Pi5 at $pi5_host"
        log_info "Please check your network connection and IP address"
    fi
    
    # Test SSH connection
    log "Testing SSH connection..."
    if ssh -o ConnectTimeout=5 -o BatchMode=yes "${pi5_user}@${pi5_host}" "echo 'SSH connection successful'" 2>/dev/null; then
        log_success "SSH connection to Pi5 successful"
    else
        log_warning "SSH connection failed"
        log_info "Make sure you have SSH key authentication set up"
        log_info "Run: ssh-copy-id ${pi5_user}@${pi5_host}"
    fi
    
    echo ""
    log_success "Configuration setup complete!"
    log_info "You can now run: ./dev-setup.sh setup"
}

show_help() {
    cat << EOF
Pi5 RAG Configuration Setup

Usage: $0 [OPTIONS]

Options:
  -i, --interactive    Interactive configuration setup
  -c, --check          Check current configuration
  -h, --help           Show this help message

Examples:
  $0 --interactive     # Set up configuration interactively
  $0 --check           # Check current configuration
EOF
}

check_config() {
    log "Configuration Check"
    log "==================="
    echo ""
    
    if [ -f "config.env" ]; then
        log_success "Configuration file found: config.env"
        echo ""
        log_info "Current configuration:"
        source config.env
        echo "  Production Host: $PRODUCTION_HOST"
        echo "  Production User: $PRODUCTION_USER"
        echo "  Production Path: $PRODUCTION_PATH"
        echo "  Service Name: $SERVICE_NAME"
        echo ""
        
        # Test connection
        log_info "Testing connection..."
        if ping -c 1 -W 1 "$PRODUCTION_HOST" >/dev/null 2>&1; then
            log_success "Pi5 is reachable"
        else
            log_warning "Pi5 is not reachable"
        fi
        
        # Test SSH
        if ssh -o ConnectTimeout=5 -o BatchMode=yes "${PRODUCTION_USER}@${PRODUCTION_HOST}" "echo 'SSH OK'" 2>/dev/null; then
            log_success "SSH connection working"
        else
            log_warning "SSH connection failed"
        fi
    else
        log_warning "No configuration file found"
        log_info "Run: $0 --interactive"
    fi
}

main() {
    case "${1:-help}" in
        -i|--interactive)
            interactive_setup
            ;;
        -c|--check)
            check_config
            ;;
        -h|--help|help)
            show_help
            ;;
        *)
            log "Unknown option: $1"
            show_help
            exit 1
            ;;
    esac
}

main "$@"
